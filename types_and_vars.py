# Declare variables with different data types
name = "Sami"    # String (text)
age = 40         # Integer (whole number)
height = 1.80    # Float (decimal number)


# Print the introduction using an f-string
print(f"Hello, my name is {name}. I am {age} years old and {height} meters tall.")

# Print calculation of age in 5 years time
print(f"In 5 years, I will be {age + 5} years old.")

# Calculate Rectangle Area ---
# Store dimensions in variables (using rect_height to avoid overwriting your height above)
width = 5.5
height = 2
print(f"The area of a {width} X {height} rectangle is {width * height}.")

# Operator Demonstrations
# Arithmetic operators chosen: Floor division (//) and Modulo (%)
print("The result (whole number) of 10 divided by 3:", 10 // 3)
print("The result (remainder) of 10 divided by 3:", 10 % 3)

# String operators: Concatenation (+) and Repetition (*)


print("-" * 20)  # Prints a line of 20 dashes for separation
print("Happy" + " " + "Coding!")  # Concatenates strings with a space in between

